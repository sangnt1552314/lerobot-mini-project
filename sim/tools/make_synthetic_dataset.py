"""Write a SYNTHETIC (fake) stand-in for the sim LiftCube dataset, for plumbing and throughput tests only.

    python sim/tools/make_synthetic_dataset.py --root /scratch/.../local/synthetic_liftcube_smoke

The features match what LeIsaac's recorder writes for LeIsaac-SO101-LiftCube-DualCam-v0
(observation.images.front / .wrist 480x640x3 AV1 video at 30 fps, observation.state (6,),
action (6,), robot_type so101_follower, task "Lift the red cube."), and it is written with
LeRobot's own LeRobotDataset.create / add_frame / save_episode / finalize, so video encoding
(libsvtav1, g=2, crf=30) and file layout are the same as a recorded dataset.

The content is NOT a demonstration: images are procedurally drawn moving shapes on a textured
background (so video decoding costs something realistic, unlike constant colours) and the joint
trajectories are smooth random curves. A policy trained on it means nothing. Never evaluate or
report policy quality from it.
"""

import argparse
import sys
from pathlib import Path

import numpy as np

JOINTS = ["shoulder_pan", "shoulder_lift", "elbow_flex", "wrist_flex", "wrist_roll", "gripper"]
TASK = "Lift the red cube."
H, W = 480, 640
MARKER = "SYNTHETIC_DATA_NOT_REAL.txt"


def features() -> dict:
    names = [f"{j}.pos" for j in JOINTS]
    video = {"dtype": "video", "shape": (H, W, 3), "names": ["height", "width", "channels"]}
    return {
        "observation.state": {"dtype": "float32", "shape": (6,), "names": names},
        "action": {"dtype": "float32", "shape": (6,), "names": names},
        "observation.images.front": dict(video),
        "observation.images.wrist": dict(video),
    }


def smooth_curve(rng: np.random.Generator, n: int, lo: float, hi: float) -> np.ndarray:
    """Sum of a few random low-frequency sinusoids, scaled into [lo, hi]."""
    t = np.linspace(0, 1, n)
    y = sum(rng.uniform(0.3, 1) * np.sin(2 * np.pi * (rng.uniform(0.2, 1.5) * t + rng.uniform())) for _ in range(3))
    y = (y - y.min()) / (np.ptp(y) + 1e-6)
    return (lo + (hi - lo) * y).astype(np.float32)


class Painter:
    """Draws a textured 'table' with a moving red square ('cube') and a moving grey bar ('arm')."""

    def __init__(self, rng: np.random.Generator, wrist: bool):
        yy, xx = np.mgrid[0:H, 0:W].astype(np.float32)
        base = np.stack([0.55 + 0.25 * xx / W, 0.5 + 0.2 * yy / H, 0.45 + 0.1 * (xx + yy) / (W + H)], -1)
        tex = rng.normal(0, 0.04, (H // 8, W // 8, 1)).repeat(8, 0).repeat(8, 1)  # blocky table texture
        self.bg = np.clip((base + tex) * 255, 0, 255).astype(np.uint8)
        self.wrist = wrist
        self.yy, self.xx = yy, xx

    def frame(self, cube_xy, arm_xy, light: float) -> np.ndarray:
        img = (self.bg.astype(np.float32) * light).clip(0, 255).astype(np.uint8)
        cx, cy = int(cube_xy[0] * W), int(cube_xy[1] * H)
        s = 70 if self.wrist else 30
        img[max(cy - s, 0) : cy + s, max(cx - s, 0) : cx + s] = (200, 30, 30)
        ax, ay = int(arm_xy[0] * W), int(arm_xy[1] * H)
        bar = (np.abs(self.xx - ax) < 25) & (self.yy < ay)
        img[bar] = (90, 90, 95)
        return img


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--root", required=True, help="Dataset directory to create (must not exist).")
    ap.add_argument("--repo-id", default="local/synthetic_liftcube_smoke")
    ap.add_argument("--episodes", type=int, default=20)
    ap.add_argument("--frames", type=int, default=200)
    ap.add_argument("--seed", type=int, default=0)
    args = ap.parse_args()

    from lerobot.datasets.lerobot_dataset import LeRobotDataset

    root = Path(args.root)
    if root.exists():
        sys.exit(f"{root} already exists; delete it first or pass another --root.")

    ds = LeRobotDataset.create(
        repo_id=args.repo_id,
        fps=30,
        features=features(),
        root=root,
        robot_type="so101_follower",
        use_videos=True,
        image_writer_threads=8,
    )
    (root / MARKER).write_text(
        "SYNTHETIC DATA - NOT REAL. Procedurally generated by sim/tools/make_synthetic_dataset.py to test\n"
        "the training pipeline and measure throughput. It contains no demonstrations. Do not train a policy\n"
        "on it for use, and do not report policy quality from it.\n"
    )

    # Ranges in LeRobot SO-101 units: arm joints -100..100, gripper 0..100.
    ranges = [(-40, 40), (-60, 20), (-30, 70), (-50, 50), (-80, 80), (5, 60)]
    for ep in range(args.episodes):
        rng = np.random.default_rng(args.seed + ep)
        n = args.frames
        action = np.stack([smooth_curve(rng, n, lo, hi) for lo, hi in ranges], 1)
        state = np.vstack([action[:1], action[:-1]]) + rng.normal(0, 0.2, action.shape).astype(np.float32)
        front, wrist = Painter(rng, wrist=False), Painter(rng, wrist=True)
        cube = np.stack([smooth_curve(rng, n, 0.3, 0.7), smooth_curve(rng, n, 0.4, 0.8)], 1)
        arm = np.stack([smooth_curve(rng, n, 0.2, 0.8), smooth_curve(rng, n, 0.2, 0.9)], 1)
        light = smooth_curve(rng, n, 0.85, 1.1)
        for i in range(n):
            ds.add_frame(
                {
                    "observation.state": state[i].astype(np.float32),
                    "action": action[i].astype(np.float32),
                    "observation.images.front": front.frame(cube[i], arm[i], light[i]),
                    "observation.images.wrist": wrist.frame(1 - arm[i], cube[i], light[i]),
                    "task": TASK,
                }
            )
        ds.save_episode()
        print(f"episode {ep + 1}/{args.episodes} saved", flush=True)
    ds.stop_image_writer()
    ds.finalize()
    print(f"SYNTHETIC dataset written to {root} ({args.episodes} episodes x {args.frames} frames)")


if __name__ == "__main__":
    main()
